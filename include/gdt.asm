%ifndef GDT_H_
%define GDT_H_

align 16
gdtr:
gdt_size: dw gdtend - gdt - 1
gdt_ptr:  dd gdt

align 16
gdt:
db 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00 ; 0x00: null segment
db 0xFF, 0xFF, 0x00, 0x00, 0x00, 0x9A, 0xCF, 0x00 ; 0x08: 32bit - code segment (kernel)
db 0xFF, 0xFF, 0x00, 0x00, 0x00, 0x92, 0xCF, 0x00 ; 0x10: 32bit - data segment (kernel)
db 0xFF, 0xFF, 0x00, 0x00, 0x00, 0x9A, 0x00, 0x00 ; 0x18: 16bit - code segment (kernel)
db 0xFF, 0xFF, 0x00, 0x00, 0x00, 0x92, 0x00, 0x00 ; 0x20: 16bit - data segment (kernel)
;                               @NOTE: ^^^^
;                                      is this really suposed to be 0? 
;                                      that means all the flags are off, which is kinda sus
;                                      previously i've used 0x8F.
gdtend:

%endif ; GDT_H_
